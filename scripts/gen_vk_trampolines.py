#!/usr/bin/env python3
"""Generate ps5/vk_ps5_trampolines.c — static Vulkan C entry points that dispatch
into Mesa RADV PS5's static ICD (vk_icdGetInstanceProcAddr in libvulkan_radeon.ps5.a).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
VK_CORE_H = Path("/usr/include/vulkan/vulkan_core.h")
OUT_C = PROJECT_ROOT / "ps5" / "vk_ps5_trampolines.c"
NM = PROJECT_ROOT / "third_party" / "ps5-kit" / "tools" / "bin" / "llvm-nm"
RT_OBJ_DIR = PROJECT_ROOT / "build" / "probe_rt_obj"

GLOBAL_PROCS = {
    "vkEnumerateInstanceVersion",
    "vkEnumerateInstanceExtensionProperties",
    "vkEnumerateInstanceLayerProperties",
}


def collect_needed_vk_symbols() -> list[str]:
    objs = sorted(str(p) for p in RT_OBJ_DIR.rglob("*.o"))
    if not objs:
        raise RuntimeError(f"No compiled objects in {RT_OBJ_DIR}")
    res = subprocess.run([str(NM), "-u", *objs], capture_output=True, text=True, check=True)
    syms: set[str] = set()
    for line in res.stdout.splitlines():
        parts = line.strip().split()
        if len(parts) == 2 and parts[0] == "U" and re.match(r"^vk[A-Z][A-Za-z0-9_]*$", parts[1]):
            syms.add(parts[1])
    return sorted(syms)


def parse_vk_prototypes(header_text: str) -> dict[str, tuple[str, list[tuple[str, str]]]]:
    """Parse VKAPI_ATTR <ret> VKAPI_CALL vkName(<params>); from vulkan_core.h."""
    rx = re.compile(
        r"VKAPI_ATTR\s+([A-Za-z0-9_*\s]+?)\s+VKAPI_CALL\s+(vk[A-Z][A-Za-z0-9_]*)\s*\(([^;]*?)\)\s*;",
        re.MULTILINE | re.DOTALL,
    )
    protos: dict[str, tuple[str, list[tuple[str, str]]]] = {}
    for m in rx.finditer(header_text):
        ret = " ".join(m.group(1).split())
        name = m.group(2)
        raw_params = " ".join(m.group(3).split())
        params: list[tuple[str, str]] = []
        if raw_params and raw_params != "void":
            for part in raw_params.split(","):
                p = part.strip()
                # Extract parameter identifier (handles array suffixes like float blendConstants[4])
                am = re.search(r"([A-Za-z_][A-Za-z0-9_]*)(\s*\[[^\]]*\])?$", p)
                if not am:
                    raise ValueError(f"Cannot parse param {p!r} in {name}")
                pname = am.group(1)
                params.append((p, pname))
        protos[name] = (ret, params)
    return protos


def is_device_proc(name: str, params: list[tuple[str, str]]) -> bool:
    if name == "vkGetDeviceProcAddr" or not params:
        return False
    return params[0][0].startswith(("VkDevice", "VkQueue", "VkCommandBuffer"))


def is_instance_proc(name: str, params: list[tuple[str, str]]) -> bool:
    if name in GLOBAL_PROCS or name in ("vkGetInstanceProcAddr", "vkCreateInstance"):
        return False
    return not is_device_proc(name, params)


def generate() -> Path:
    needed = collect_needed_vk_symbols()
    needed_set = set(needed)
    protos = parse_vk_prototypes(VK_CORE_H.read_text(encoding="utf-8"))

    missing = [s for s in needed if s not in protos]
    if missing:
        raise RuntimeError(f"Could not find prototypes in {VK_CORE_H}: {missing}")

    has_gdpa = "vkGetDeviceProcAddr" in needed_set
    cached_syms = [n for n in needed if n != "vkGetInstanceProcAddr"]
    device_procs = [n for n in needed if is_device_proc(n, protos[n][1])]
    instance_procs = [n for n in needed if is_instance_proc(n, protos[n][1])]
    non_global_procs = [
        n for n in cached_syms if n not in GLOBAL_PROCS and n != "vkCreateInstance"
    ]

    lines = [
        "/* Auto-generated by scripts/gen_vk_trampolines.py — do not hand-edit. */",
        "/* Static Vulkan C trampolines with cached dispatch table into libvulkan_radeon.ps5.a. */",
        "",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "#include <vulkan/vulkan.h>",
        "",
        "extern PFN_vkVoidFunction vk_icdGetInstanceProcAddr(VkInstance instance, const char *pName);",
        "",
        "static VkInstance g_ps5_vk_inst = VK_NULL_HANDLE;",
        "static VkDevice g_ps5_vk_dev = VK_NULL_HANDLE;",
        "",
    ]

    for name in cached_syms:
        lines.append(f"static PFN_{name} pfn_{name} = NULL;")
    lines.append("")

    # Helper: resolve vkGetDeviceProcAddr (using cached slot if present in needed)
    if has_gdpa:
        gdpa_resolve_lines = [
            "    PFN_vkGetDeviceProcAddr gdpa = __atomic_load_n(&pfn_vkGetDeviceProcAddr, __ATOMIC_ACQUIRE);",
            "    if (!gdpa && inst != VK_NULL_HANDLE) {",
            '        gdpa = (PFN_vkGetDeviceProcAddr)vk_icdGetInstanceProcAddr(inst, "vkGetDeviceProcAddr");',
            "        if (gdpa) __atomic_store_n(&pfn_vkGetDeviceProcAddr, gdpa, __ATOMIC_RELEASE);",
            "    }",
        ]
    else:
        gdpa_resolve_lines = [
            '    PFN_vkGetDeviceProcAddr gdpa = (inst != VK_NULL_HANDLE) ? (PFN_vkGetDeviceProcAddr)vk_icdGetInstanceProcAddr(inst, "vkGetDeviceProcAddr") : NULL;',
        ]

    # Batch loader: instance-level procs (+ vkDestroyDevice if present)
    inst_load_syms = [
        n for n in needed if is_instance_proc(n, protos[n][1]) or n == "vkDestroyDevice"
    ]
    lines += [
        "__attribute__((unused))",
        "static void ps5_vk_load_instance_procs(VkInstance inst) {",
        "    if (inst == VK_NULL_HANDLE) return;",
    ]
    for name in inst_load_syms:
        lines.append(
            f'    __atomic_store_n(&pfn_{name}, (PFN_{name})vk_icdGetInstanceProcAddr(inst, "{name}"), __ATOMIC_RELEASE);'
        )
    lines += ["}", ""]

    # Batch loader: device-level procs
    lines += [
        "__attribute__((unused))",
        "static void ps5_vk_load_device_procs(VkInstance inst, VkDevice dev) {",
        "    if (dev == VK_NULL_HANDLE) return;",
    ]
    if device_procs:
        lines += gdpa_resolve_lines
        for name in device_procs:
            lines += [
                "    {",
                f'        PFN_{name} fn = gdpa ? (PFN_{name})gdpa(dev, "{name}") : NULL;',
                f'        if (!fn && inst != VK_NULL_HANDLE) fn = (PFN_{name})vk_icdGetInstanceProcAddr(inst, "{name}");',
                f"        __atomic_store_n(&pfn_{name}, fn, __ATOMIC_RELEASE);",
                "    }",
            ]
    else:
        lines += ["    (void)inst;"]
    lines += ["}", ""]

    # Cold lazy-fallback helpers for trampolines
    lines += [
        "__attribute__((noinline, cold, unused))",
        "static PFN_vkVoidFunction ps5_vk_resolve_global_or_instance(const char *name, int is_global) {",
        "    VkInstance inst = is_global ? VK_NULL_HANDLE : __atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE);",
        "    if (!is_global && inst == VK_NULL_HANDLE) return NULL;",
        "    return vk_icdGetInstanceProcAddr(inst, name);",
        "}",
        "",
        "__attribute__((noinline, cold, unused))",
        "static PFN_vkVoidFunction ps5_vk_resolve_device(const char *name) {",
        "    VkInstance inst = __atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE);",
        "    VkDevice dev = __atomic_load_n(&g_ps5_vk_dev, __ATOMIC_ACQUIRE);",
        "    PFN_vkVoidFunction fn = NULL;",
        "    if (dev != VK_NULL_HANDLE) {",
    ]
    for gl in gdpa_resolve_lines:
        lines.append("    " + gl)
    lines += [
        "        if (gdpa) fn = gdpa(dev, name);",
        "    }",
        "    if (!fn && inst != VK_NULL_HANDLE) {",
        "        fn = vk_icdGetInstanceProcAddr(inst, name);",
        "    }",
        "    return fn;",
        "}",
        "",
    ]

    for name in needed:
        ret, params = protos[name]
        param_decl = ", ".join(p for p, _ in params) if params else "void"
        arg_pass = ", ".join(pn for _, pn in params)

        if name == "vkGetInstanceProcAddr":
            lines += [
                f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
                f"    return vk_icdGetInstanceProcAddr({arg_pass});",
                "}",
                "",
            ]
            continue

        if name == "vkGetDeviceProcAddr":
            lines += [
                f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
                "    PFN_vkGetDeviceProcAddr fn = __atomic_load_n(&pfn_vkGetDeviceProcAddr, __ATOMIC_ACQUIRE);",
                "    if (__builtin_expect(!fn, 0)) {",
                "        VkInstance inst = __atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE);",
                "        if (inst != VK_NULL_HANDLE) {",
                '            fn = (PFN_vkGetDeviceProcAddr)vk_icdGetInstanceProcAddr(inst, "vkGetDeviceProcAddr");',
                "            if (fn) __atomic_store_n(&pfn_vkGetDeviceProcAddr, fn, __ATOMIC_RELEASE);",
                "        }",
                "    }",
                f"    return fn ? fn({arg_pass}) : NULL;",
                "}",
                "",
            ]
            continue

        if name == "vkCreateInstance":
            lines += [
                f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
                "    PFN_vkCreateInstance fn = __atomic_load_n(&pfn_vkCreateInstance, __ATOMIC_ACQUIRE);",
                "    if (__builtin_expect(!fn, 0)) {",
                '        fn = (PFN_vkCreateInstance)vk_icdGetInstanceProcAddr(VK_NULL_HANDLE, "vkCreateInstance");',
                "        if (fn) __atomic_store_n(&pfn_vkCreateInstance, fn, __ATOMIC_RELEASE);",
                "    }",
                "    if (!fn) return VK_ERROR_INITIALIZATION_FAILED;",
                f"    VkResult vr = fn({arg_pass});",
                "    if (vr == VK_SUCCESS && pInstance) {",
                "        __atomic_store_n(&g_ps5_vk_inst, *pInstance, __ATOMIC_RELEASE);",
                "        ps5_vk_load_instance_procs(*pInstance);",
                "    }",
                "    return vr;",
                "}",
                "",
            ]
            continue

        if name == "vkDestroyInstance":
            lines += [
                f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
                "    PFN_vkDestroyInstance fn = __atomic_load_n(&pfn_vkDestroyInstance, __ATOMIC_ACQUIRE);",
                "    if (__builtin_expect(!fn, 0) && instance != VK_NULL_HANDLE) {",
                '        fn = (PFN_vkDestroyInstance)vk_icdGetInstanceProcAddr(instance, "vkDestroyInstance");',
                "    }",
                "    if (fn) fn(instance, pAllocator);",
                "    VkInstance cur = __atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE);",
                "    if (instance != VK_NULL_HANDLE && cur == instance) {",
                "        __atomic_store_n(&g_ps5_vk_inst, VK_NULL_HANDLE, __ATOMIC_RELEASE);",
                "        __atomic_store_n(&g_ps5_vk_dev, VK_NULL_HANDLE, __ATOMIC_RELEASE);",
            ]
            for s in non_global_procs:
                lines.append(f"        __atomic_store_n(&pfn_{s}, NULL, __ATOMIC_RELEASE);")
            lines += [
                "    }",
                "}",
                "",
            ]
            continue

        if name == "vkCreateDevice":
            lines += [
                f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
                "    PFN_vkCreateDevice fn = __atomic_load_n(&pfn_vkCreateDevice, __ATOMIC_ACQUIRE);",
                "    if (__builtin_expect(!fn, 0)) {",
                "        VkInstance inst = __atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE);",
                "        if (inst != VK_NULL_HANDLE) {",
                '            fn = (PFN_vkCreateDevice)vk_icdGetInstanceProcAddr(inst, "vkCreateDevice");',
                "            if (fn) __atomic_store_n(&pfn_vkCreateDevice, fn, __ATOMIC_RELEASE);",
                "        }",
                "    }",
                "    if (!fn) return VK_ERROR_INITIALIZATION_FAILED;",
                f"    VkResult vr = fn({arg_pass});",
                "    if (vr == VK_SUCCESS && pDevice) {",
                "        __atomic_store_n(&g_ps5_vk_dev, *pDevice, __ATOMIC_RELEASE);",
                "        ps5_vk_load_device_procs(__atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE), *pDevice);",
                "    }",
                "    return vr;",
                "}",
                "",
            ]
            continue

        if name == "vkDestroyDevice":
            lines += [
                f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
                "    PFN_vkDestroyDevice fn = __atomic_load_n(&pfn_vkDestroyDevice, __ATOMIC_ACQUIRE);",
                "    if (__builtin_expect(!fn, 0) && device != VK_NULL_HANDLE) {",
                "        VkInstance inst = __atomic_load_n(&g_ps5_vk_inst, __ATOMIC_ACQUIRE);",
            ]
            for gl in gdpa_resolve_lines:
                lines.append("    " + gl)
            lines += [
                '        if (gdpa) fn = (PFN_vkDestroyDevice)gdpa(device, "vkDestroyDevice");',
                '        if (!fn && inst != VK_NULL_HANDLE) fn = (PFN_vkDestroyDevice)vk_icdGetInstanceProcAddr(inst, "vkDestroyDevice");',
                "    }",
                "    if (fn) fn(device, pAllocator);",
                "    VkDevice cur = __atomic_load_n(&g_ps5_vk_dev, __ATOMIC_ACQUIRE);",
                "    if (device != VK_NULL_HANDLE && cur == device) {",
                "        __atomic_store_n(&g_ps5_vk_dev, VK_NULL_HANDLE, __ATOMIC_RELEASE);",
            ]
            for s in device_procs:
                lines.append(f"        __atomic_store_n(&pfn_{s}, NULL, __ATOMIC_RELEASE);")
            lines += [
                "    }",
                "}",
                "",
            ]
            continue

        pfn_type = f"PFN_{name}"
        if is_device_proc(name, params):
            resolve_expr = f'({pfn_type})ps5_vk_resolve_device("{name}")'
        else:
            is_global_flag = 1 if name in GLOBAL_PROCS else 0
            resolve_expr = f'({pfn_type})ps5_vk_resolve_global_or_instance("{name}", {is_global_flag})'

        lines += [
            f"VKAPI_ATTR {ret} VKAPI_CALL {name}({param_decl}) {{",
            f"    {pfn_type} fn = __atomic_load_n(&pfn_{name}, __ATOMIC_ACQUIRE);",
            "    if (__builtin_expect(!fn, 0)) {",
            f"        fn = {resolve_expr};",
            f"        if (fn) __atomic_store_n(&pfn_{name}, fn, __ATOMIC_RELEASE);",
            "    }",
        ]
        if ret == "void":
            lines.append(f"    if (fn) fn({arg_pass});")
        elif ret == "VkResult":
            lines.append(f"    return fn ? fn({arg_pass}) : VK_ERROR_EXTENSION_NOT_PRESENT;")
        else:
            lines.append(f"    return fn ? fn({arg_pass}) : ({ret})0;")
        lines += ["}", ""]

    OUT_C.write_text("\n".join(lines), encoding="utf-8")
    print(f"[ok] Generated {len(needed)} Vulkan ICD trampolines -> {OUT_C}")
    return OUT_C


if __name__ == "__main__":
    generate()
